#!/usr/bin/env node
/**
 * Generates the ES module shims client extension bundles alias their imports to, so the bundle
 * uses the host's React and SDK instead of shipping its own copies:
 *
 *   react                    -> shims/react.js
 *   react/jsx-runtime        -> shims/jsx-runtime.js
 *   @orbis-homelab/sdk/client    -> shims/orbis-sdk-client.js
 *                               (also written as shims/belvedere-sdk-client.js, the file name
 *                               build scripts written before the rename alias to)
 *
 * Each shim re-exports names from `window.__ORBIS__` (set by the PWA before any extension
 * script runs). The SDK names are the value exports of `sdk/client.ts`; the React names are the
 * exports of the installed `react` package.
 *
 * Usage:  node sdk/scripts/make-shims.mjs [outDir]      (default: ./shims)
 *
 * esbuild example:
 *   alias: { react: 'shims/react.js', 'react/jsx-runtime': 'shims/jsx-runtime.js',
 *            '@orbis-homelab/sdk/client': 'shims/orbis-sdk-client.js' }
 */
import { mkdirSync, readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const IDENTIFIER = /^[A-Za-z_$][\w$]*$/;
const RESERVED = new Set(['default']);

/** Value names exported by `sdk/client.ts` (`export { A, B as C } from '...'`; types are skipped). */
export function parseSdkExports(source) {
  if (/^\s*export\s+\*/m.test(source)) {
    throw new Error('sdk/client.ts must list its exports explicitly (no `export *`)');
  }
  const names = [];
  for (const match of source.matchAll(/^export\s+\{([^}]*)\}\s+from\s+['"][^'"]+['"]/gm)) {
    for (const part of (match[1] ?? '').split(',')) {
      const specifier = part.trim();
      if (specifier === '' || specifier.startsWith('type ')) continue;
      const name = specifier.split(/\s+as\s+/).pop() ?? '';
      if (!IDENTIFIER.test(name)) throw new Error(`Unsupported export specifier: "${specifier}"`);
      names.push(name);
    }
  }
  return [...new Set(names)];
}

/** Source of one shim module re-exporting `names` from the host global `globalKey`. */
export function shimSource({ globalKey, names, withDefault }) {
  const exportable = [...new Set(names)].filter(
    (name) => IDENTIFIER.test(name) && !RESERVED.has(name),
  );
  const lines = [
    '// Generated by sdk/scripts/make-shims.mjs. Do not edit.',
    // `__BELVEDERE__` is the name before 0.1.0: a bundle rebuilt now still runs on an older host.
    'const host = globalThis.__ORBIS__ ?? globalThis.__BELVEDERE__;',
    "if (!host) throw new Error('Orbis Homelab host is missing: load this bundle from the Orbis Homelab PWA');",
    `const mod = host.${globalKey};`,
  ];
  if (withDefault) lines.push('export default mod;');
  for (const name of exportable) lines.push(`export const ${name} = mod.${name};`);
  return `${lines.join('\n')}\n`;
}

/** File name -> content of the shims (the SDK one under its current and its legacy file name). */
export function generateShims({ sdkSource, reactExports, jsxRuntimeExports }) {
  const sdkShim = shimSource({
    globalKey: 'sdk',
    names: parseSdkExports(sdkSource),
    withDefault: false,
  });
  return {
    'react.js': shimSource({ globalKey: 'react', names: reactExports, withDefault: true }),
    'jsx-runtime.js': shimSource({
      globalKey: 'jsxRuntime',
      names: jsxRuntimeExports,
      withDefault: false,
    }),
    'orbis-sdk-client.js': sdkShim,
    'belvedere-sdk-client.js': sdkShim,
  };
}

function main() {
  const here = dirname(fileURLToPath(import.meta.url));
  const require = createRequire(import.meta.url);
  const outDir = resolve(process.argv[2] ?? 'shims');
  const files = generateShims({
    sdkSource: readFileSync(join(here, '..', 'client.ts'), 'utf8'),
    reactExports: Object.keys(require('react')),
    jsxRuntimeExports: Object.keys(require('react/jsx-runtime')),
  });
  mkdirSync(outDir, { recursive: true });
  for (const [name, content] of Object.entries(files)) {
    writeFileSync(join(outDir, name), content);
    process.stdout.write(`${join(outDir, name)}\n`);
  }
}

/**
 * True when this file is the program being run. Node reports `import.meta.url` with symlinks
 * resolved, so the path in `argv[1]` must be resolved the same way: a script started through a
 * symlinked file or directory (a linked checkout, `npm link`, a `node_modules/.bin` entry) would
 * otherwise never run `main()` and silently generate nothing.
 */
function isMainModule() {
  if (!process.argv[1]) return false;
  try {
    return realpathSync(resolve(process.argv[1])) === fileURLToPath(import.meta.url);
  } catch {
    return false;
  }
}

if (isMainModule()) main();
