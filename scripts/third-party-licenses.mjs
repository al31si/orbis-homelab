#!/usr/bin/env node
/**
 * Builds THIRD_PARTY_NOTICES.md: the licence of every production dependency, the ones that end up
 * in the Docker image (backend) or are bundled into the web app. Development tools are not listed:
 * nothing of them is distributed.
 *
 *   node scripts/third-party-licenses.mjs            write THIRD_PARTY_NOTICES.md
 *   node scripts/third-party-licenses.mjs --check    fail if a licence is not permissive or the
 *                                                    committed file is out of date (run in CI)
 *
 * Needs `npm ci` first: licences are read from the installed packages.
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUTPUT = path.join(root, 'THIRD_PARTY_NOTICES.md');

/** Licences that allow redistribution inside an Apache-2.0 project with attribution only. */
const PERMISSIVE = new Set([
  'MIT',
  'ISC',
  'BSD-2-Clause',
  'BSD-3-Clause',
  'Apache-2.0',
  '0BSD',
  'BlueOak-1.0.0',
]);

/**
 * Licences accepted with a reason, for a named package only (a different package with the same
 * licence still fails the check and has to be reviewed):
 *  - web-push, MPL-2.0: file-level copyleft. Used unmodified as a dependency, so the obligation is
 *    to keep the notice and point to its source, which the notices file does;
 *  - wouter, Unlicense: a public domain dedication.
 */
const REVIEWED = new Map([
  ['web-push', 'MPL-2.0'],
  ['wouter', 'Unlicense'],
]);

const isAllowed = ({ name }, license) => PERMISSIVE.has(license) || REVIEWED.get(name) === license;

const lock = JSON.parse(readFileSync(path.join(root, 'package-lock.json'), 'utf8'));

function packageEntries() {
  const found = new Map();
  for (const [location, entry] of Object.entries(lock.packages)) {
    if (!location.includes('node_modules/') || entry.dev || entry.devOptional || entry.link)
      continue;
    const dir = path.join(root, location);
    const manifestPath = path.join(dir, 'package.json');
    if (!existsSync(manifestPath)) {
      throw new Error(`${location} is not installed: run npm ci first`);
    }
    const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));
    found.set(`${manifest.name}@${manifest.version}`, { dir, manifest });
  }
  return [...found.values()].sort((a, b) =>
    `${a.manifest.name}@${a.manifest.version}`.localeCompare(
      `${b.manifest.name}@${b.manifest.version}`,
    ),
  );
}

function licenseOf(manifest) {
  if (typeof manifest.license === 'string') return manifest.license;
  if (manifest.license?.type) return manifest.license.type;
  if (Array.isArray(manifest.licenses)) return manifest.licenses.map((l) => l.type).join(' OR ');
  return 'UNKNOWN';
}

function licenseText(dir) {
  const file = readdirSync(dir).find((name) => /^(licen[cs]e|copying)(\.[a-z]+)?$/i.test(name));
  return file ? readFileSync(path.join(dir, file), 'utf8').trim() : null;
}

function repositoryOf(manifest) {
  const repo =
    typeof manifest.repository === 'string' ? manifest.repository : manifest.repository?.url;
  return repo?.replace(/^git\+/, '').replace(/\.git$/, '') ?? manifest.homepage ?? '';
}

function build(entries) {
  const lines = [
    '# Third-party notices',
    '',
    'Orbis Homelab is licensed under the Apache License 2.0 (see [LICENSE](LICENSE)). It includes the',
    'open source packages below. Each one keeps its own licence, reproduced here as the licence',
    'requires. Generated by `scripts/third-party-licenses.mjs` from the production dependencies in',
    '`package-lock.json`: do not edit by hand.',
    '',
    'Packages under the MPL-2.0 (`web-push`) are used unmodified; their source code is available at the',
    'address given in their section.',
    '',
    'Fonts: none are bundled; the interface uses the fonts of the visitor\u2019s system. Icons and the',
    'app logo are original work of this project and are covered by the Apache License 2.0.',
    '',
    '| Package | Version | Licence |',
    '| ------- | ------- | ------- |',
  ];
  for (const { manifest } of entries) {
    lines.push(`| ${manifest.name} | ${manifest.version} | ${licenseOf(manifest)} |`);
  }
  for (const { dir, manifest } of entries) {
    const text = licenseText(dir);
    lines.push(
      '',
      `## ${manifest.name} ${manifest.version}`,
      '',
      `Licence: ${licenseOf(manifest)}`,
    );
    const repo = repositoryOf(manifest);
    if (repo) lines.push(`Source: ${repo}`);
    lines.push(
      '',
      text
        ? ['```text', text, '```'].join('\n')
        : '_The package ships no licence file; see its repository._',
    );
  }
  return `${lines.join('\n')}\n`;
}

const entries = packageEntries();
const problems = entries
  .filter(({ manifest }) => !isAllowed(manifest, licenseOf(manifest)))
  .map(
    ({ manifest }) =>
      `${manifest.name}@${manifest.version}: licence ${licenseOf(manifest)} is not in the allowed list`,
  );
const missing = entries
  .filter(({ dir }) => licenseText(dir) === null)
  .map(({ manifest }) => `${manifest.name}@${manifest.version}: no licence file`);
const content = build(entries);

if (process.argv.includes('--check')) {
  if (!existsSync(OUTPUT) || readFileSync(OUTPUT, 'utf8') !== content) {
    problems.push(
      'THIRD_PARTY_NOTICES.md is missing or out of date: run node scripts/third-party-licenses.mjs',
    );
  }
  if (problems.length > 0) {
    for (const problem of problems) process.stderr.write(`${problem}\n`);
    process.exit(1);
  }
  process.stdout.write(
    `${entries.length} production packages, licences allowed, notices up to date\n`,
  );
} else {
  writeFileSync(OUTPUT, content);
  process.stdout.write(`wrote ${path.relative(root, OUTPUT)}: ${entries.length} packages\n`);
  for (const line of [...problems, ...missing]) process.stderr.write(`warning: ${line}\n`);
}
